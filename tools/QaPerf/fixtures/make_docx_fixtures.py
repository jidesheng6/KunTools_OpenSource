"""Generate the Word fixtures used by tools/QaPerf (word.pdf / large scenarios).

Layout produced under testdata/perf/:
  word/assets/inline_chart.png       small inline image embedded in every sample
  word/batch/batch_001..050.docx     2-page samples (mixed zh/en, table, one image)
  large/large_30p.docx               30-page document (explicit page breaks)

Every page break is explicit so the page count is deterministic even though
python-docx itself does not paginate.

Usage:
  python make_docx_fixtures.py [--repo-root <path>]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Inches, Pt
from PIL import Image, ImageDraw

CJK_FONT = "Microsoft YaHei"

BATCH_COUNT = 50
LARGE_PAGES = 30

ZH_LINES = [
    "本文档由 QA 性能基线工具生成，用于量化批量转换的耗时与内存。",
    "中文字符、标点（，。；：！？）、全角空格与英文混排都出现在同一段落里。",
    "第二段用于增加文本体积，使 Aspose.Words 的分页与排版路径真实执行。",
    "表格与图片是转换耗时的主要来源之一，因此每个样本都包含这两类元素。",
]

EN_LINES = [
    "This fixture is generated by the QA perf harness to measure batch conversion cost.",
    "Mixed content: Latin glyphs 0123456789, quotes \"q\", and zh text in one run.",
    "A short paragraph keeps the layout engine busy without inflating the file size.",
    "Each sample stays below 200 KB so the whole fixture set fits the 20 MB budget.",
]


def set_cjk(run, name: str = CJK_FONT) -> None:
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def add_paragraph(doc: Document, text: str, *, bold: bool = False, size: int = 11) -> None:
    paragraph = doc.add_paragraph()
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    set_cjk(run)


def add_table(doc: Document, rows: list[list[str]]) -> None:
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for r, row in enumerate(rows):
        for c, cell_text in enumerate(row):
            cell = table.cell(r, c)
            cell.text = ""
            paragraph = cell.paragraphs[0]
            run = paragraph.add_run(cell_text)
            run.bold = r == 0
            run.font.size = Pt(10)
            set_cjk(run)


def build_inline_image(path: Path) -> Path:
    """Small gradient + bar chart image (about 8 KB) embedded in every sample."""
    path.parent.mkdir(parents=True, exist_ok=True)
    width, height = 320, 180
    image = Image.new("RGB", (width, height), (248, 249, 251))
    draw = ImageDraw.Draw(image)
    for y in range(height):
        shade = 242 - int(28 * y / height)
        draw.line([(0, y), (width, y)], fill=(shade, shade + 2, 250))
    bars = [0.42, 0.71, 0.55, 0.88, 0.63, 0.79]
    bar_width = width // (len(bars) * 2)
    for index, ratio in enumerate(bars):
        x0 = bar_width * (2 * index + 1) // 2
        y0 = height - 20 - int((height - 50) * ratio)
        draw.rectangle([x0, y0, x0 + bar_width, height - 20], fill=(51, 122, 183))
    draw.line([(12, height - 20), (width - 12, height - 20)], fill=(120, 120, 120), width=2)
    draw.text((12, 8), "QA perf fixture 2026", fill=(60, 60, 60))
    image.save(path, format="PNG", optimize=True)
    return path


def new_document() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = CJK_FONT
    style.font.size = Pt(11)
    rpr = style.element.get_or_add_rPr()
    rpr.rFonts.set(qn("w:eastAsia"), CJK_FONT)
    return doc


def add_page_body(doc: Document, index: int, page: int, image: Path) -> None:
    heading = doc.add_heading(level=1)
    run = heading.add_run(f"批量样本 {index:03d} · Batch sample {index:03d} · 第 {page} 页")
    set_cjk(run, CJK_FONT)

    add_paragraph(doc, ZH_LINES[(index + page) % len(ZH_LINES)])
    add_paragraph(doc, EN_LINES[(index + page) % len(EN_LINES)])
    add_table(
        doc,
        [
            ["项目 Item", "数值 Value", "说明 Note"],
            [f"样本 #{index:03d}", f"{index * 17 % 97}", "中文单元格 CJK cell"],
            ["耗时 Elapsed", f"{0.4 + (index % 13) * 0.03:.2f} s", "由 harness 记录"],
            ["内存 Working set", f"{180 + index % 90} MB", "峰值采样"],
        ],
    )
    add_paragraph(doc, ZH_LINES[(index + page + 1) % len(ZH_LINES)])

    if page == 1:
        picture = doc.add_paragraph()
        picture.alignment = WD_ALIGN_PARAGRAPH.CENTER
        picture.add_run().add_picture(str(image), width=Inches(2.2))
        caption = doc.add_paragraph()
        caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
        caption_run = caption.add_run("图 1 内联小图（320×180 PNG）")
        caption_run.italic = True
        caption_run.font.size = Pt(9)
        set_cjk(caption_run)


def write_batch_sample(root: Path, index: int, image: Path) -> Path:
    doc = new_document()
    add_page_body(doc, index, 1, image)
    doc.add_page_break()
    add_page_body(doc, index, 2, image)
    target = root / "word" / "batch" / f"batch_{index:03d}.docx"
    target.parent.mkdir(parents=True, exist_ok=True)
    doc.save(target)
    return target


def write_large_document(root: Path, image: Path) -> Path:
    """30 pages with explicit breaks, kept under the Aspose evaluation paragraph cap.

    The evaluation build of Aspose.Words 26.1 stops loading at 202 paragraphs, so a dense
    30-page file (300+ paragraphs) renders as 16 pages. This layout keeps roughly 180
    paragraphs while still forcing 30 pages, which makes the conversion measurable end to end.
    """
    doc = new_document()
    for page in range(1, LARGE_PAGES + 1):
        heading = doc.add_heading(level=1)
        run = heading.add_run(f"长文档第 {page} 页 · Large document page {page}")
        set_cjk(run, CJK_FONT)
        for line in range(2):
            add_paragraph(doc, ZH_LINES[(page + line) % len(ZH_LINES)])
            add_paragraph(doc, EN_LINES[(page + line) % len(EN_LINES)])
        if page % 15 == 0:
            add_table(
                doc,
                [
                    ["指标 Metric", "第 " + str(page) + " 页"],
                    ["段落 Paragraphs", str(page * 3)],
                ],
            )
        if page == 1:
            picture = doc.add_paragraph()
            picture.add_run().add_picture(str(image), width=Inches(2.6))
        if page < LARGE_PAGES:
            doc.add_page_break()
    target = root / "large" / "large_30p.docx"
    target.parent.mkdir(parents=True, exist_ok=True)
    doc.save(target)
    return target


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=None)
    args = parser.parse_args()

    root = Path(args.repo_root) if args.repo_root else Path(__file__).resolve().parents[3]
    perf = root / "testdata" / "perf"
    perf.mkdir(parents=True, exist_ok=True)

    image = build_inline_image(perf / "word" / "assets" / "inline_chart.png")
    written = [write_batch_sample(perf, index, image) for index in range(1, BATCH_COUNT + 1)]
    written.append(write_large_document(perf, image))

    total = 0
    for path in written:
        size = path.stat().st_size
        total += size
        if size > 200 * 1024:
            print(f"OVER BUDGET: {path} = {size} bytes")
    print(f"docx fixtures: {len(written)} files, {total} bytes total, max "
          f"{max(p.stat().st_size for p in written)} bytes")
    print(f"inline image: {image} = {image.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
