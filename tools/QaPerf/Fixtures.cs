using System.Globalization;

namespace DocumentTools.QaPerf;

internal sealed class FixtureGroup
{
    public string Name { get; set; } = string.Empty;

    /// <summary>Repository-relative path (report friendly, no machine-specific prefix).</summary>
    public string Path { get; set; } = string.Empty;

    public int Count { get; set; }

    public long TotalBytes { get; set; }

    public long MaxBytes { get; set; }

    public string Generator { get; set; } = string.Empty;
}

internal sealed class FixtureSummary
{
    public const long PerFileBudget = 200 * 1024;

    public const long TotalBudget = 20L * 1024 * 1024;

    public List<FixtureGroup> Groups { get; set; } = new();

    public List<string> Notes { get; set; } = new();

    public List<string> Warnings { get; set; } = new();

    public long TotalBytes => Groups.Sum(group => group.TotalBytes);

    public long MaxFileBytes => Groups.Count == 0 ? 0 : Groups.Max(group => group.MaxBytes);
}

/// <summary>Raised when a fixture group is missing and cannot be generated by the harness itself.</summary>
internal sealed class FixtureMissingException : Exception
{
    public FixtureMissingException(string message)
        : base(message)
    {
    }
}

/// <summary>
/// Ensures every fixture a scenario needs exists. Nothing here touches Aspose on purpose: the
/// first Aspose type loaded must happen inside the measured round, otherwise "cold start" is a lie.
/// </summary>
internal static class FixtureSetup
{
    public static FixtureSummary Ensure(RepoLayout layout, IReadOnlyList<string> families)
    {
        var summary = new FixtureSummary();

        if (families.Contains(ScenarioSet.FamilyWordPdf) || families.Contains(ScenarioSet.FamilyLarge))
        {
            summary.Groups.AddRange(DescribeDocx(layout, summary));
        }

        if (families.Contains(ScenarioSet.FamilyImage))
        {
            ImageFixtures.Ensure(layout.ImageRoot, summary.Notes);
            summary.Groups.Add(DescribeGroup("png", layout.ImageRoot, "px_*.png", "SkiaSharp 现场生成（1600x1200 渐变+方块噪声+斑点）", layout));
        }

        if (families.Contains(ScenarioSet.FamilyLarge))
        {
            PdfFixtureWriter.EnsureLarge(layout.PdfRoot, summary.Notes);
            summary.Groups.Add(DescribeGroup("pdf-200p", layout.PdfRoot, "pages200.pdf", "PdfFixtureWriter 手写 PDF 1.4（200 页，Helvetica）", layout));
        }

        if (families.Contains(ScenarioSet.FamilyMerge))
        {
            string mergeDirectory = PdfFixtureWriter.EnsureMergeParts(layout.PdfRoot, summary.Notes);
            summary.Groups.Add(DescribeGroup("pdf-merge20", mergeDirectory, "part_*.pdf", "PdfFixtureWriter 手写 PDF 1.4（20 个 2 页文档）", layout));
        }

        ApplyBudget(summary);
        return summary;
    }

    private static List<FixtureGroup> DescribeDocx(RepoLayout layout, FixtureSummary summary)
    {
        string batchRoot = layout.WordBatchRoot;
        string largePath = Path.Combine(layout.LargeRoot, "large_30p.docx");
        string[] batch = Directory.Exists(batchRoot)
            ? Directory.GetFiles(batchRoot, "batch_*.docx")
            : Array.Empty<string>();

        if (batch.Length < 50 || !File.Exists(largePath))
        {
            throw new FixtureMissingException(
                "缺少 docx 夹具：需要 testdata\\perf\\word\\batch\\batch_001..050.docx 与 testdata\\perf\\large\\large_30p.docx。\r\n" +
                "生成命令：python tools\\QaPerf\\fixtures\\make_docx_fixtures.py");
        }

        summary.Notes.Add("docx 夹具（python-docx 生成：中英文段落 + 4x3 表格 + 内联 PNG，显式分页）已存在，直接复用");

        var groups = new List<FixtureGroup>
        {
            DescribeGroup(
                "docx-batch",
                batchRoot,
                "batch_*.docx",
                "python-docx：每份 2 页（中英文段落 + 4x3 表格 + 内联 PNG）",
                layout)
        };

        if (HasLargeDocx(layout, largePath))
        {
            groups.Add(DescribeGroup(
                "docx-large",
                layout.LargeRoot,
                "large_30p.docx",
                "python-docx：单文件 30 页（显式分页，每页 1 标题 + 4 段，每 15 页一张表，首页含图；共 188 段，低于评估版 202 段截断线）",
                layout));
        }

        return groups;
    }

    private static bool HasLargeDocx(RepoLayout layout, string largePath)
        => File.Exists(largePath) && Directory.Exists(layout.LargeRoot);

    private static FixtureGroup DescribeGroup(
        string name,
        string directory,
        string pattern,
        string generator,
        RepoLayout layout)
    {
        string[] files = Directory.Exists(directory)
            ? Directory.GetFiles(directory, pattern)
            : Array.Empty<string>();

        long max = 0;
        long total = 0;
        foreach (string file in files)
        {
            long length = new FileInfo(file).Length;
            total += length;
            max = Math.Max(max, length);
        }

        return new FixtureGroup
        {
            Name = name,
            Path = Relative(layout, directory),
            Count = files.Length,
            TotalBytes = total,
            MaxBytes = max,
            Generator = generator
        };
    }

    private static string Relative(RepoLayout layout, string path)
    {
        string relative = Path.GetRelativePath(layout.RepoRoot, path);
        return relative.Replace('/', '\\');
    }

    private static void ApplyBudget(FixtureSummary summary)
    {
        foreach (FixtureGroup group in summary.Groups)
        {
            if (group.MaxBytes > FixtureSummary.PerFileBudget)
            {
                summary.Warnings.Add(string.Format(
                    CultureInfo.InvariantCulture,
                    "{0} 单文件最大 {1:0.0} KB，超出 200 KB 预算",
                    group.Name,
                    group.MaxBytes / 1024d));
            }
        }

        if (summary.TotalBytes > FixtureSummary.TotalBudget)
        {
            summary.Warnings.Add(string.Format(
                CultureInfo.InvariantCulture,
                "夹具合计 {0:0.0} MB，超出 20 MB 预算",
                summary.TotalBytes / (1024d * 1024d)));
        }
    }
}
